"""Crawl Chewy's public shelter directory (city pages) and write shelters-data.js.

Walks city pages via their "nearby cities" links, up to MAX_PER_STATE city pages
per state, and collects each shelter's name, city, state, wish-list item count,
logo and Chewy page. Polite: one request at a time with a delay.

Usage:  python tools/crawl_shelters.py
"""
import html as htmlmod
import json
import re
import time
import urllib.request
from pathlib import Path

BASE = "https://www.chewy.com"
UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0 Safari/537.36"
MAX_PAGES = 260
MAX_PER_STATE = 4
DELAY = 0.6
OUT = Path(__file__).resolve().parent.parent / "shelters-data.js"

CITY_RE = re.compile(r'href="(/g/animal-shelters-in-[a-z0-9-]+_g\d+)"')
BLOCK_RE = re.compile(r'<div class="shelter-search-result">(.*?)<hr class="kib-divider', re.S)


def get(path):
    req = urllib.request.Request(BASE + path, headers={"User-Agent": UA, "Accept-Language": "en-US"})
    with urllib.request.urlopen(req, timeout=30) as r:
        return r.read().decode("utf-8", "replace")


def text(s):
    return htmlmod.unescape(re.sub(r"<[^>]+>", " ", s)).replace("\xa0", " ")


LOGO_RE = re.compile(r'businessPageUrl:"([a-z0-9-]+_b\d+)",logoUrl:"([^"]+)"')


def parse(page, shelters):
    # logos for every result live in the embedded page data (cards past the first few lazy-load them)
    logos = {slug: url.encode().decode("unicode_escape") for slug, url in LOGO_RE.findall(page)}
    for block in BLOCK_RE.findall(page):
        m = re.search(r'href="/g/([a-z0-9-]+_b\d+)', block)
        if not m:
            continue
        slug = m.group(1)
        if slug in shelters:
            continue
        name = re.search(r'<h4 class="shelter-search-result__header">(.*?)</h4>', block, re.S)
        loc = re.search(r'class="shelter-search-result__location[^"]*">(.*?)</div>', block, re.S)
        logo = re.search(r'<img[^>]+src="(https://prd-[^"]+shelter-app[^"]+)"', block)
        wishes = re.search(r"(\d[\d,]*)\s*Wish List\s*Items?", text(block))
        loc_t = re.sub(r"\s+", " ", text(loc.group(1))).strip() if loc else ""
        lm = re.search(r"(?:^|,\s*)([A-Za-z .'-]+),\s*([A-Z]{2})\b", loc_t.split("(")[0])
        city, st = (lm.group(1).strip(), lm.group(2)) if lm else ("", "")
        shelters[slug] = {
            "n": re.sub(r"\s+", " ", text(name.group(1))).strip() if name else slug,
            "c": city.title() if city.isupper() else city,
            "s": st,
            "w": int(wishes.group(1).replace(",", "")) if wishes else 0,
            "l": logo.group(1) if logo else (logos.get(slug) if (logos.get(slug) or "").startswith("https://") else ""),
        }


def main():
    queue = list(dict.fromkeys(CITY_RE.findall(get("/g/animal-shelters-and-rescues"))))
    seen = set(queue)
    per_state, shelters, fetched = {}, {}, 0
    st_of = lambda u: (re.search(r"-([a-z]{2})_g\d+$", u) or [None, ""])[1]
    while queue and fetched < MAX_PAGES:
        queue.sort(key=lambda u: per_state.get(st_of(u), 0))
        url = queue.pop(0)
        st = st_of(url)
        if per_state.get(st, 0) >= MAX_PER_STATE:
            continue
        try:
            page = get(url)
        except Exception as e:  # noqa: BLE001
            print("skip", url, e)
            continue
        fetched += 1
        per_state[st] = per_state.get(st, 0) + 1
        parse(page, shelters)
        for u in CITY_RE.findall(page):
            if u not in seen:
                seen.add(u)
                queue.append(u)
        if fetched % 20 == 0:
            print(f"{fetched} pages, {len(shelters)} shelters, {len(per_state)} states", flush=True)
        time.sleep(DELAY)

    rows = [[k, v["n"], v["c"], v["s"], v["w"], v["l"]] for k, v in shelters.items() if v["s"]]
    rows.sort(key=lambda r: (-r[4], r[1]))
    OUT.write_text(
        "// Generated by tools/crawl_shelters.py from Chewy's public shelter directory.\n"
        f"// {time.strftime('%Y-%m-%d')} · {len(rows)} shelters · row = [chewySlug, name, city, state, wishListItems, logoUrl]\n"
        "window.SHELTERS = " + json.dumps(rows, ensure_ascii=False, separators=(",", ":")) + ";\n",
        encoding="utf-8",
    )
    print(f"done: {fetched} pages, {len(rows)} shelters, {len(per_state)} states -> {OUT}")


if __name__ == "__main__":
    main()

"""Read the wish-list preview of the top shelters in each state and write wishes-data.js.

Needs shelters-data.js (from crawl_shelters.py). For up to PER_STATE shelters per state
(most wish-list items first) it fetches the shelter's public Chewy page and reads the
wish-list tiles shown there: item name, price, need level and image. Gift cards skipped.

Usage:  python tools/crawl_wishes.py
"""
import html as htmlmod
import json
import re
import time
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0 Safari/537.36"
PER_STATE = 5
DELAY = 0.6
TILE_RE = re.compile(r'<div class="wishlist-item">(.*?)<div class="kib-stepper__controls-wrapper">', re.S)


def get(url):
    req = urllib.request.Request(url, headers={"User-Agent": UA, "Accept-Language": "en-US"})
    with urllib.request.urlopen(req, timeout=30) as r:
        return r.read().decode("utf-8", "replace")


def clean(s):
    return re.sub(r"\s+", " ", htmlmod.unescape(re.sub(r"<[^>]+>", " ", s))).strip()


def kind(name):
    n = name.lower()
    if "litter" in n:
        return "litter"
    if any(w in n for w in ("treat", "chew stick", "jerky", "biscuit", "bone", "lickable")):
        return "treats"
    if any(w in n for w in ("food", "formula", "kibble", "entree", "pate", "milk replacer", "recipe")):
        return "food"
    if any(w in n for w in ("toy", "ball", "wand", "catnip", "squeak", "plush", "rope")):
        return "toys"
    if any(w in n for w in ("bed", "blanket", "mat", "crate", "kennel", "carrier")):
        return "beds"
    if any(w in n for w in ("shampoo", "flea", "medic", "supplement", "wipes", "pad", "bag", "cleaner", "deodor")):
        return "care"
    return "other"


def main():
    src = (ROOT / "shelters-data.js").read_text(encoding="utf-8")
    rows = json.loads(src[src.index("window.SHELTERS = ") + 18:].rstrip().rstrip(";"))
    picked, per = [], {}
    for r in sorted(rows, key=lambda r: -r[4]):
        if r[4] >= 3 and per.get(r[3], 0) < PER_STATE:
            per[r[3]] = per.get(r[3], 0) + 1
            picked.append(r)
    print(f"{len(picked)} shelters to read", flush=True)

    wishes = []
    for i, (slug, *_rest) in enumerate(picked, 1):
        try:
            page = get(f"https://www.chewy.com/g/{slug}")
        except Exception as e:  # noqa: BLE001
            print("skip", slug, e)
            continue
        for t in TILE_RE.findall(page):
            img = re.search(r'<img[^>]+src="([^"]+)"', t)
            name = re.search(r'class="wishlist-item__name">(.*?)</div>', t, re.S)
            price = re.search(r'product-price__amount[^"]*">\s*\$([\d,.]+)\s*<', t)
            need = re.search(r'class="wishlist-item__status"><div>(.*?)</div>', t, re.S)
            if not (img and name and price):
                continue
            nm = clean(name.group(1))
            if "gift card" in nm.lower():
                continue
            src_img = img.group(1)
            src_img = ("https:" + src_img if src_img.startswith("//") else src_img)
            src_img = re.sub(r"\._SS\d+_", "._SS400_", src_img)
            wishes.append([slug, nm, float(price.group(1).replace(",", "")),
                           1 if need and "most" in need.group(1).lower() else 0, src_img, kind(nm)])
        if i % 25 == 0:
            print(f"{i}/{len(picked)} shelters, {len(wishes)} wishes", flush=True)
        time.sleep(DELAY)

    wishes.sort(key=lambda w: (-w[3], w[2]))
    (ROOT / "wishes-data.js").write_text(
        "// Generated by tools/crawl_wishes.py from shelters' public Chewy wish lists.\n"
        f"// {time.strftime('%Y-%m-%d')} · {len(wishes)} wishes · row = [shelterSlug, item, price, mostNeeded(1/0), imageUrl, kind]\n"
        "window.WISHES = " + json.dumps(wishes, ensure_ascii=False, separators=(",", ":")) + ";\n",
        encoding="utf-8",
    )
    print(f"done: {len(wishes)} wishes from {len(picked)} shelters")


if __name__ == "__main__":
    main()
